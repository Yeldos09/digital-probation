const ru: Record<string, string> = Object.fromEntries(rows.map(([key, value]) => [key, value]))
const kk: Record<string, string> = Object.fromEntries(rows.map(([key, , value]) => [key, value]))

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const table = lang === 'kk' ? kk : ru
  let value = table[key] ?? ru[key] ?? key
  if (vars) {
    for (const [name, item] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(item))
    }
  }
  return value
}

export function L(key: string, vars?: Record<string, string | number>): Localized {
  return { ru: translate('ru', key, vars), kk: translate('kk', key, vars) }
}

export function L2(
  key: string,
  vars: { ru: Record<string, string | number>; kk: Record<string, string | number> },
): Localized {
  return { ru: translate('ru', key, vars.ru), kk: translate('kk', key, vars.kk) }
}
